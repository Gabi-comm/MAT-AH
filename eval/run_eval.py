"""MAT-AH evaluation on the synthetic demo set. Writes eval/results.md.

Usage (from the repo root, Ollama running):
  .venv\\Scripts\\python -m eval.run_eval            # index a fresh copy of the demo data, then evaluate
  .venv\\Scripts\\python -m eval.run_eval --no-sagot # retrieval only
"""
import argparse
import json
import os
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name):
    return [json.loads(l) for l in (ROOT / "eval" / name).read_text(encoding="utf-8").splitlines() if l.strip()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-sagot", action="store_true")
    a = ap.parse_args()

    tmp = Path(tempfile.mkdtemp(prefix="matah_eval_"))
    files = tmp / "My Files"
    subprocess.run([sys.executable, str(ROOT / "scripts" / "make_demo_data.py"), "--out", str(files)], check=True)
    os.environ["MATAH_DB"] = str(tmp / "eval.db")

    from backend import folders, hanap, llm, sagot, scan, visual, winsearch
    visual.installed = lambda: False  # the eval set has no images; keep it about text retrieval
    winsearch.available = lambda: False  # temp folders are not in the Windows index anyway
    llm.vision_model = lambda: None
    from backend.index import VECTORS, connect

    con = connect(tmp / "eval.db")
    folders.add_root(con, str(files))
    t = time.perf_counter()
    scan.run(con)
    index_s = time.perf_counter() - t
    VECTORS.load(con)

    queries = load("queries.jsonl")
    rows, per_lang = [], {}
    for mode in ("keyword", "hybrid"):
        for item in queries:
            res = hanap.search(con, item["q"], mode=mode, use_llm=False)
            names = [h["file"]["name"] for h in res["hits"]]
            rank = names.index(item["file"]) + 1 if item["file"] in names else None
            page_ok = None
            if rank and item.get("page"):
                page_ok = res["hits"][rank - 1]["locator"].get("page") == item["page"]
            hit3 = bool(rank and rank <= 3)
            rows.append({**item, "mode": mode, "rank": rank, "hit3": hit3, "page_ok": page_ok,
                         "retrieve_ms": res["timings"]["retrieve"], "parse_ms": res["timings"]["parse"]})
            per_lang.setdefault((mode, item["lang"]), []).append(hit3)

    def rate(mode, lang=None):
        xs = [r["hit3"] for r in rows if r["mode"] == mode and (lang is None or r["lang"] == lang)]
        return sum(xs), len(xs)

    sagot_rows = []
    if not a.no_sagot and llm.available():
        for item in load("sagot.jsonl"):
            t = time.perf_counter()
            ans = sagot.answer(con, item["q"])
            wall = (time.perf_counter() - t) * 1000
            if item["expect"] is None:
                ok = ans["status"] != "grounded"
                kind = "unanswerable"
            else:
                text = (ans.get("answer") or "")
                ok = ans["status"] == "grounded" and any(e.lower() in text.lower() for e in item["expect"])
                kind = "answerable"
            sagot_rows.append({"q": item["q"], "kind": kind, "ok": ok, "status": ans["status"],
                               "answer": ans.get("answer") or ans.get("rejected") or "", "timings": ans["timings"],
                               "wall_ms": round(wall), "problems": ans.get("problems", [])})

    med = lambda xs: round(statistics.median(xs), 1) if xs else None
    out = ["# MAT-AH evaluation", "",
           f"Run: {time.strftime('%Y-%m-%d %H:%M')} on this laptop. Data: the synthetic demo set "
           f"({sum(1 for _ in files.rglob('*') if _.is_file())} files, generated by `scripts/make_demo_data.py`).",
           f"Models: chat `{llm.chat_model()}`, embeddings `{llm.EMBED_MODEL if llm.embed_available() else 'none'}`, "
           "OCR RapidOCR (ONNX). Everything ran locally.", "",
           f"Full index of the demo folder: {index_s:.1f} s.", "",
           f"## Search (Hanap): top-3 hit rate, {len(queries)} queries", "",
           "| Queries | Keyword only | Hybrid (keyword + meaning) |", "|---|---|---|"]
    n_of = lambda l: sum(1 for x in queries if l is None or x["lang"] == l)
    for lang, label in (("en", f"English ({n_of('en')})"), ("fil", f"Filipino ({n_of('fil')})"), ("taglish", f"Taglish ({n_of('taglish')})"), (None, f"**All ({len(queries)})**")):
        k, n = rate("keyword", lang)
        h, _ = rate("hybrid", lang)
        out.append(f"| {label} | {k}/{n} ({k / n:.0%}) | {h}/{n} ({h / n:.0%}) |")
    page_rows = [r for r in rows if r["mode"] == "hybrid" and r.get("page")]
    out += ["", f"Right page for page-specific queries (hybrid): "
                f"{sum(1 for r in page_rows if r['page_ok'])}/{len(page_rows)}.", "",
            f"Median timings (hybrid): parse {med([r['parse_ms'] for r in rows if r['mode'] == 'hybrid'])} ms, "
            f"retrieve {med([r['retrieve_ms'] for r in rows if r['mode'] == 'hybrid'])} ms.", ""]
    misses = [r for r in rows if r["mode"] == "hybrid" and not r["hit3"]]
    if misses:
        out += ["Hybrid misses:", ""] + [f"- `{r['q']}` → expected {r['file']}, rank {r['rank']}" for r in misses] + [""]

    if sagot_rows:
        ans_ok = [r for r in sagot_rows if r["kind"] == "answerable"]
        un_ok = [r for r in sagot_rows if r["kind"] == "unanswerable"]
        out += [f"## Answers (Sagot): {len(sagot_rows)} questions, {len(un_ok)} unanswerable", "",
                f"- Correct grounded answers: {sum(r['ok'] for r in ans_ok)}/{len(ans_ok)}",
                f"- Correct \"insufficient evidence\" on unanswerable: {sum(r['ok'] for r in un_ok)}/{len(un_ok)}",
                f"- Median generate {med([r['timings'].get('generate', 0) for r in sagot_rows])} ms, "
                f"verify {med([r['timings'].get('verify', 0) for r in sagot_rows])} ms, "
                f"end to end {med([r['wall_ms'] for r in sagot_rows])} ms", "",
                "| Question | Expected | Result | Answer |", "|---|---|---|---|"]
        for r in sagot_rows:
            out.append(f"| {r['q']} | {r['kind']} | {'✅' if r['ok'] else '❌'} {r['status']} | "
                       f"{r['answer'].replace('|', '/').replace(chr(10), ' ')[:120]} |")
    elif not a.no_sagot:
        out += ["## Answers (Sagot)", "", "Skipped: no local chat model was available."]

    (ROOT / "eval" / "results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")  # the table has ✅/❌; the Windows console is cp1252
    print("\n".join(out))


if __name__ == "__main__":
    main()
